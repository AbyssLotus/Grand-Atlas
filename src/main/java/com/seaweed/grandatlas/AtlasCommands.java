package com.seaweed.grandatlas;

import com.mojang.brigadier.arguments.StringArgumentType;
import com.seaweed.grandatlas.core.AtlasCore;
import com.seaweed.grandatlas.core.ColumnSample;
import com.seaweed.grandatlas.core.landform.Landform;
import com.seaweed.grandatlas.core.macro.Macro;
import com.seaweed.grandatlas.core.micro.MesoKind;
import com.seaweed.grandatlas.core.micro.MesoSite;
import com.seaweed.grandatlas.core.macro.MacroSite;
import com.seaweed.grandatlas.core.province.Province;
import com.seaweed.grandatlas.world.CoreHandle;
import net.minecraft.commands.CommandSourceStack;
import net.minecraft.commands.Commands;
import net.minecraft.commands.SharedSuggestionProvider;
import net.minecraft.core.BlockPos;
import net.minecraft.network.chat.Component;
import net.minecraft.world.level.levelgen.densityfunction.SamplerContext;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.event.RegisterCommandsEvent;
import org.jspecify.annotations.Nullable;

/**
 * <ul>
 *   <li>{@code /grandatlas where}: the column's tag stack and what the core decided there</li>
 *   <li>{@code /grandatlas locate <landform|macro|site>}: the nearest province holding that landform, macro, or meso site</li>
 *   <li>{@code /grandatlas seed}: the core seed, for {@code gradlew preview --seed} to render this world</li>
 * </ul>
 */
@EventBusSubscriber(modid = GrandAtlas.MOD_ID)
public final class AtlasCommands {
    private AtlasCommands() {}

    @SubscribeEvent
    static void register(RegisterCommandsEvent event) {
        event.getDispatcher().register(Commands.literal(GrandAtlas.MOD_ID)
                .requires(Commands.hasPermission(Commands.LEVEL_GAMEMASTERS))
                .then(Commands.literal("where").executes(ctx -> where(ctx.getSource())))
                .then(Commands.literal("seed").executes(ctx -> seed(ctx.getSource())))
                .then(Commands.literal("locate")
                        .then(Commands.argument("landform", StringArgumentType.word())
                                .suggests((ctx, builder) -> {
                                    AtlasCore core = core(ctx.getSource());
                                    return core == null ? builder.buildFuture()
                                            : SharedSuggestionProvider.suggest(java.util.stream.Stream.of(
                                                    core.landforms().stream().map(Landform::id),
                                                    core.macros().kinds().stream().map(Macro::id),
                                                    java.util.Arrays.stream(MesoKind.values()).map(MesoKind::id),
                                                    com.seaweed.grandatlas.core.world.WorldField.ISLAND_SEAS.stream(),
                                                    java.util.stream.Stream.of("worm_bore", "mega_cavern", "underground_sea", "rift", "great_rift", "the_hollow", "great_geode", "titans_grave")).flatMap(s -> s), builder);
                                })
                                .executes(ctx -> locate(ctx.getSource(), StringArgumentType.getString(ctx, "landform"))))));
    }

    private static @Nullable AtlasCore core(CommandSourceStack source) {
        return CoreHandle.coreFrom(source.getLevel().getChunkSource().randomState()
                .createClimateSampler(SamplerContext.EMPTY_UNCACHED));
    }

    private static @Nullable AtlasCore coreOrFail(CommandSourceStack source) {
        AtlasCore core = core(source);
        if (core == null) {
            source.sendFailure(Component.literal("This dimension isn't generated by Grand Atlas."));
        }
        return core;
    }

    private static int where(CommandSourceStack source) {
        AtlasCore core = coreOrFail(source);
        if (core == null) return 0;
        BlockPos pos = BlockPos.containing(source.getPosition());
        ColumnSample c = core.column(pos.getX(), pos.getZ());
        String report = String.format(
                "Grand Atlas at %d, %d%n  %s  (province %d,%d, %s)%n"
                        + "  surface y %.1f = datum %.1f + relief %.1f%n"
                        + "  temperature %.2f  humidity %.2f  continentalness %.2f%n"
                        + "  surface biome %s  biome here %s",
                pos.getX(), pos.getZ(), String.join(" → ", c.tags()), c.provinceX(), c.provinceZ(), c.transition().id(),
                c.height(), c.datum(), c.relief(),
                c.temperature(), c.humidity(), c.continentalness(),
                c.biome().id(), core.biomeAt(c, pos.getX(), pos.getY(), pos.getZ()).id());
        source.sendSuccess(() -> Component.literal(report), false);
        return 1;
    }

    private static int locate(CommandSourceStack source, String id) {
        AtlasCore core = coreOrFail(source);
        if (core == null) return 0;
        BlockPos pos = BlockPos.containing(source.getPosition());
        if (id.equals("the_hollow") || id.equals("great_geode") || id.equals("titans_grave")) {
            int kind = id.equals("the_hollow") ? com.seaweed.grandatlas.core.SetPieces.HOLLOW : id.equals("great_geode")
                    ? com.seaweed.grandatlas.core.SetPieces.GEODE : com.seaweed.grandatlas.core.SetPieces.TITAN;
            double[] m = core.setPieces().nearest(kind, pos.getX(), pos.getZ());
            if (m == null) {
                source.sendFailure(Component.literal("None nearby."));
                return 0;
            }
            int distance = (int) Math.hypot(m[0] - pos.getX(), m[2] - pos.getZ());
            source.sendSuccess(() -> Component.literal(String.format("Nearest %s: %d %d %d (%d blocks), about %.0f across",
                    id.replace('_', ' '), (int) m[0], (int) m[1], (int) m[2], distance, m[3])), false);
            return distance;
        }
        if (id.equals("underground_sea")) {
            double[] m = core.megaCaverns().nearestSea(pos.getX(), pos.getZ());
            if (m == null) {
                source.sendFailure(Component.literal("No underground sea within ~10 km."));
                return 0;
            }
            int distance = (int) Math.hypot(m[0] - pos.getX(), m[1] - pos.getZ());
            source.sendSuccess(() -> Component.literal(String.format("Nearest underground sea: middle %d %d, water at y %d (%d blocks), about %.0f across",
                    (int) m[0], (int) m[1], (int) m[3], distance, m[2])), false);
            return distance;
        }
        if (id.equals("mega_cavern")) {
            double[] m = core.megaCaverns().nearest(pos.getX(), pos.getZ());
            if (m == null) {
                source.sendFailure(Component.literal("No mega-cavern within ~5 km."));
                return 0;
            }
            int distance = (int) Math.hypot(m[0] - pos.getX(), m[1] - pos.getZ());
            source.sendSuccess(() -> Component.literal(String.format("Nearest mega-cavern: middle %d %d %d (%d blocks), about %.0f across",
                    (int) m[0], (int) m[3], (int) m[1], distance, m[2])), false);
            return distance;
        }
        if (id.equals("rift") || id.equals("great_rift")) {
            double[] r = core.passages().nearestRift(pos.getX(), pos.getZ(), id.equals("great_rift"));
            if (r == null) {
                source.sendFailure(Component.literal("No " + id + " nearby."));
                return 0;
            }
            int distance = (int) Math.hypot(r[0] - pos.getX(), r[1] - pos.getZ());
            source.sendSuccess(() -> Component.literal(String.format("Nearest %s: middle at %d %d, top y %d (%d blocks)",
                    r[3] > 0 ? "great rift" : "rift", (int) r[0], (int) r[1], (int) r[2], distance)), false);
            return distance;
        }
        if (id.equals("worm_bore")) {
            double[] bore = core.passages().nearestBore(pos.getX(), pos.getZ());
            if (bore == null) {
                source.sendFailure(Component.literal("No worm bore within ~8 km."));
                return 0;
            }
            int distance = (int) Math.hypot(bore[0] - pos.getX(), bore[1] - pos.getZ());
            source.sendSuccess(() -> Component.literal(String.format("Nearest worm bore: starts at %d %d %d (%d blocks), %s",
                    (int) bore[0], (int) bore[3], (int) bore[1], distance, bore[2] > 0 ? "opening in the ground" : "underground")), false);
            return distance;
        }
        if (com.seaweed.grandatlas.core.world.WorldField.ISLAND_SEAS.contains(id)) {
            double[] sea = core.world().nearestIslandSea(id, pos.getX(), pos.getZ());
            if (sea == null) {
                source.sendFailure(Component.literal("No " + id + " within ~150 km."));
                return 0;
            }
            int distance = (int) Math.hypot(sea[0] - pos.getX(), sea[1] - pos.getZ());
            source.sendSuccess(() -> Component.literal(String.format("Nearest %s: centre %d %d (%d blocks), about %.0f km across",
                    id, (int) sea[0], (int) sea[1], distance, sea[2] * 2 / 1000)), false);
            return distance;
        }
        Macro macro = core.macro(id);
        if (macro != null) {
            MacroSite site = core.findMacro(macro, pos.getX(), pos.getZ());
            if (site == null) {
                source.sendFailure(Component.literal("No " + id + " within ~100 km."));
                return 0;
            }
            int distance = (int) Math.hypot(site.x() - pos.getX(), site.z() - pos.getZ());
            source.sendSuccess(() -> Component.literal(String.format(
                    "Nearest %s: centre %d %d (%d blocks), about %.1f km across",
                    id, (int) site.x(), (int) site.z(), distance, site.radius() * 2 / 1000)), false);
            return distance;
        }
        for (MesoKind kind : MesoKind.values()) {
            if (!kind.id().equals(id)) continue;
            MesoSite site = core.features().find(kind, pos.getX(), pos.getZ(), 40);
            if (site == null) {
                source.sendFailure(Component.literal("No " + id + " within ~30 km."));
                return 0;
            }
            int distance = (int) Math.hypot(site.x() - pos.getX(), site.z() - pos.getZ());
            String parts = site.micros().stream().filter(m -> m.present()).map(m -> m.kind.id())
                    .collect(java.util.stream.Collectors.groupingBy(s -> s, java.util.TreeMap::new, java.util.stream.Collectors.counting()))
                    .toString();
            source.sendSuccess(() -> Component.literal(String.format("Nearest %s: centre %d %d (%d blocks), %d blocks across, %s",
                    id, (int) site.x(), (int) site.z(), distance, (int) (site.radius() * 2), parts)), false);
            return distance;
        }
        Landform target = core.landform(id);
        if (target == null) {
            source.sendFailure(Component.literal("No landform, macro or site '" + id + "'."));
            return 0;
        }
        Province p = core.mosaic().find(target, pos.getX(), pos.getZ(), 48);
        if (p == null) {
            source.sendFailure(Component.literal("No " + id + " within ~75 km."));
            return 0;
        }
        int x = (int) p.x(), z = (int) p.z();
        int distance = (int) Math.hypot(x - pos.getX(), z - pos.getZ());
        source.sendSuccess(() -> Component.literal(String.format(
                "Nearest %s province centre: %d %d (%d blocks; centres are in warped space, so within ~450 blocks)",
                id, x, z, distance)), false);
        return distance;
    }

    private static int seed(CommandSourceStack source) {
        AtlasCore core = coreOrFail(source);
        if (core == null) return 0;
        long seed = core.seed();
        source.sendSuccess(() -> Component.literal("Grand Atlas core seed: " + seed
                + "  (gradlew preview -Pargs=\"--seed " + seed + "\")"), false);
        return 1;
    }
}
